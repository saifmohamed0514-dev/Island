import Foundation
import CoreGraphics
struct ModuleSmoke {
 static func run() throws {
  precondition(IslandPresetRules.sanitize([0,-1,5,5,15,1441]) == [5,15])
  precondition(IslandPresetRules.sanitize([]) == [25])
  precondition(IslandPresetRules.sanitize(Array(1...20)).count == 12)
  precondition(IslandDial.minutes(x:0,y:-10,maximum:120) == 1)
  precondition(IslandDial.minutes(x:10,y:0,maximum:120) == 30)
  precondition(IslandDial.minutes(x:0,y:10,maximum:120) == 60)
  precondition(IslandDial.minutes(x:-10,y:0,maximum:120) == 90)
  precondition(IslandDial.minutes(x:.nan,y:0,maximum:120) == 1)
  var prefs = IslandModulePreferences();prefs.enabled = [];prefs.order = [.focus,.focus];prefs.start = .notes;prefs.normalize()
  precondition(prefs.order.count == NotchViews.allCases.count && prefs.order.first == .focus)
  precondition(prefs.enabled == [.dashboard] && prefs.start == .dashboard)
  prefs.enabled = [.notes,.focus,.notes];prefs.start = .notes;prefs.normalize()
  precondition(prefs.enabled == [.focus,.notes] && prefs.start == .notes)
  let restored = try JSONDecoder().decode(IslandModulePreferences.self,from:JSONEncoder().encode(prefs))
  precondition(restored.enabled == prefs.enabled && restored.order == prefs.order)
  var drag = IslandDialDrag()
  _ = drag.value(x:sin(6.2)*50,y:-cos(6.2)*50,current:119,maximum:120)
  precondition(drag.value(x:sin(0.05)*50,y:-cos(0.05)*50,current:119,maximum:120) == 120)
  drag = IslandDialDrag()
  _ = drag.value(x:sin(0.05)*50,y:-cos(0.05)*50,current:1,maximum:120)
  precondition(drag.value(x:sin(6.2)*50,y:-cos(6.2)*50,current:1,maximum:120) == 1)
  precondition(drag.value(x:0,y:0,current:1,maximum:120) == nil)
  let short = IslandCycleRules.next(phase:"Focus",completed:0,work:25,short:5,long:15)
  precondition(short.phase == "Break" && short.completed == 1 && short.minutes == 5)
  let long = IslandCycleRules.next(phase:"Focus",completed:3,work:25,short:5,long:15)
  precondition(long.phase == "Long Break" && long.completed == 4 && long.minutes == 15)
  precondition(IslandCycleRules.next(phase:"Break",completed:4,work:40,short:5,long:15).minutes == 40)
  precondition(IslandCycleRules.next(phase:"Focus",completed:0,work:25,short:.nan,long:15).minutes == 5)
  let leftScreen = CGRect(x:-1920,y:0,width:1920,height:1080)
  precondition(IslandWindowLayout.right.rectangle(in:leftScreen) == CGRect(x:-960,y:0,width:960,height:1080))
  let aboveScreen = CGRect(x:0,y:1080,width:1920,height:1080)
  precondition(IslandWindowLayout.top.accessibilityRectangle(in:aboveScreen,primaryTop:1080) == CGRect(x:0,y:-1080,width:1920,height:540))
  precondition(IslandWindowLayout.maximize.rectangle(in:leftScreen) == leftScreen)
  precondition(IslandCompactLayout.width(camera:185,kind:.timer) < 400)
  precondition(IslandCompactLayout.width(camera:185,kind:.idle) == 185)
  precondition(IslandCompactLayout.width(camera:185,kind:.hud) == IslandCompactLayout.width(camera:185,kind:.timer))
  precondition(IslandWidget.slots("bad").count == 4)
  precondition(IslandWidget.slots("battery,day").prefix(2) == [.battery,.day])
  precondition(IslandScheduleRules.profile(minute:540,start:540,end:1020) == "Work")
  precondition(IslandScheduleRules.profile(minute:1020,start:540,end:1020) == "Minimal")
  precondition(IslandScheduleRules.profile(minute:60,start:1320,end:360) == "Work")
  precondition(IslandScheduleRules.profile(minute:700,start:1320,end:360) == "Minimal")
  precondition(IslandScheduleRules.profile(minute:400,start:400,end:400) == "Minimal")
  let key="saved:"+UUID().uuidString
  precondition(IslandScheduleRules.selection(profile:"Work",work:key,minimal:"Minimal",available:[key]) == key)
  precondition(IslandScheduleRules.selection(profile:"Minimal",work:key,minimal:"Work",available:[key]) == "Work")
  precondition(IslandScheduleRules.selection(profile:"Work",work:key,minimal:"Minimal",available:[]) == "Work")
  precondition(IslandScheduleRules.selection(profile:"Minimal",work:"Work",minimal:"saved:bad",available:["saved:bad"]) == "Minimal")
  precondition(IslandScheduleRules.selection(profile:"Work",work:"bad",minimal:"Minimal",available:["bad"]) == "Work")
  precondition(IslandCompactLayout.width(camera:185,kind:.music,musicControls:true)==313 && IslandCompactLayout.width(camera:185,kind:.music)==253)
  precondition(IslandCompactLayout.showsMusicControls(kind:.music,hovering:true,closed:true,enabled:true))
  precondition(!IslandCompactLayout.showsMusicControls(kind:.timer,hovering:true,closed:true,enabled:true))
  precondition(!IslandCompactLayout.showsMusicControls(kind:.music,hovering:false,closed:true,enabled:true))
  precondition(!IslandCompactLayout.showsMusicControls(kind:.music,hovering:true,closed:false,enabled:true))
  precondition(!IslandCompactLayout.showsMusicControls(kind:.music,hovering:true,closed:true,enabled:false))
  print("PASS: 43 dial, preset, cycle, module and compact display geometry checks")
 }
}
