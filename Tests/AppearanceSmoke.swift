import Foundation
@main struct AppearanceSmoke {
 @MainActor static func main() {
  var count=0
  func check(_ value:Bool) { precondition(value,"Appearance check \(count+1)");count+=1 }
  var p=IslandAppearancePreferences();p.widthAdjustment = -40
  check(p.width(base:189,physical:185)==185)
  check(p.width(base:185,physical:0)==145)
  p.widthAdjustment = .nan;p.pausedArtworkOpacity = .infinity;p.outline="invalid";p.notchlessStyle="invalid";p.outlineColor="invalid";p.normalize()
  check(p.widthAdjustment==0 && p.pausedArtworkOpacity==0.65)
  check(p.outline=="off" && p.notchlessStyle=="pill" && p.outlineColor=="blue")
  p.widthAdjustment=500;p.normalize();check(p.widthAdjustment==120)
  p.hideTitleExtras=true;check(p.title("Song (Official Video)")=="Song")
  check(p.title("Song (Live)")=="Song (Live)")
  check(p.title("(Official Audio)")=="(Official Audio)")
  let suite="IslandAppearanceTests."+UUID().uuidString,defaults=UserDefaults(suiteName:suite)!
  defer { defaults.removePersistentDomain(forName:suite) }
  defaults.set("kept",forKey:"island.notes")
  let store=IslandAppearanceStore(defaults:defaults);store.set(\.outline,"color");store.set(\.pausedArtworkOpacity,0.1)
  check(store.preferences.pausedArtworkOpacity==0.2)
  let restored=IslandAppearanceStore(defaults:defaults)
  check(restored.preferences.outline=="color" && restored.preferences.pausedArtworkOpacity==0.2)
  check(defaults.string(forKey:"island.notes")=="kept")
  check((try? JSONDecoder().decode(IslandAppearancePreferences.self,from:JSONEncoder().encode(restored.preferences)))==restored.preferences)
  check(IslandHUDRules.label(value:2,relativeDB:false)=="100%")
  check(IslandHUDRules.label(value:.nan,relativeDB:false)=="0%")
  check(IslandHUDRules.label(value:0,relativeDB:true)=="Muted")
  check(IslandHUDRules.label(value:0.5,relativeDB:true)=="-6 dB")
  check(IslandHUDRules.label(value:0.00001,relativeDB:true)=="-60 dB")
  check(IslandHUDRules.duration(.infinity)==1.5)
  check(IslandHUDRules.duration(-1)==0.6 && IslandHUDRules.duration(20)==8)
  var swipe=IslandSwipeAccumulator()
  check(swipe.consume(x:-25,y:0,began:true,momentum:false,time:1,natural:true)==nil)
  check(swipe.consume(x:-25,y:0,began:false,momentum:false,time:1.1,natural:true)==true)
  check(swipe.consume(x:-90,y:0,began:false,momentum:false,time:1.2,natural:true)==nil)
  check(swipe.consume(x:50,y:0,began:true,momentum:true,time:1.3,natural:true)==nil)
  check(swipe.consume(x:50,y:0,began:true,momentum:false,time:2,natural:true)==false)
  check(swipe.consume(x:50,y:0,began:true,momentum:false,time:3,natural:false)==true)
  check(swipe.consume(x:1,y:50,began:true,momentum:false,time:4,natural:true)==nil)
  check(swipe.consume(x:.nan,y:0,began:false,momentum:false,time:4.1,natural:true)==nil)
  check(swipe.consume(x:-50,y:0,began:false,momentum:false,time:4.2,natural:true)==true)
  var lock=IslandLockPreferences()
  check(!lock.enabled && !lock.privateDetails)
  lock.widgets=["calendar","music","calendar","invalid"];lock.offset = .nan;lock.style="wrong";lock.normalize()
  check(lock.widgets==["music","calendar"] && lock.offset==0 && lock.style=="glass")
  let screen=CGRect(x:-1920,y:1080,width:1920,height:1080),frame=lock.panelFrame(screen:screen)
  check(frame.midX==screen.midX && frame.minY>=screen.minY && frame.maxY<=screen.maxY)
  let small=CGRect(x:0,y:0,width:400,height:600),smallFrame=lock.panelFrame(screen:small)
  check(smallFrame.width<=small.width && smallFrame.height<=small.height && smallFrame.maxY<=small.maxY)
  check(IslandLockPreferences.batteryTime(-1)==nil && IslandLockPreferences.batteryTime(.nan)==nil)
  check(IslandLockPreferences.batteryTime(3660)=="1h 1m remaining")
  let lockStore=IslandLockStore(defaults:defaults);lockStore.set(\.privateDetails,true);lockStore.toggle("calendar",false)
  check(!lockStore.preferences.widgets.contains("calendar"))
  check(IslandLockStore(defaults:defaults).preferences.privateDetails)
  let before=lockStore.preferences.widgets;lockStore.move(before[0],by:-1)
  check(lockStore.preferences.widgets==before)
  lockStore.move(before[1],by:1);check(lockStore.preferences.widgets[0]=="music" && lockStore.preferences.widgets[2]==before[1])
  check(defaults.string(forKey:"island.notes")=="kept")
  let choices=IslandLockPreferences.available.map { IslandLockWidgetRow(widget:$0,section:"choice") },positions=lockStore.preferences.widgets.filter { $0 != "music" }.map { IslandLockWidgetRow(widget:$0,section:"order") }
  let rowIDs=(choices+positions).map(\.id);check(Set(rowIDs).count==rowIDs.count)
  print("PASS: \(count) production appearance/HUD/swipe/lock-widget checks; camera protection, limits, title cleanup, private persistence, gain formatting and one action per gesture")
 }
}
